import { neon } from '@neondatabase/serverless';

if (!process.env.DATABASE_URL) {
  throw new Error('DATABASE_URL is required. Set it in .env.local before migrating.');
}

const sql = neon(process.env.DATABASE_URL);

await sql`
  CREATE TABLE IF NOT EXISTS articles (
    slug TEXT PRIMARY KEY,
    title VARCHAR(180) NOT NULL,
    summary VARCHAR(500) NOT NULL,
    image_url TEXT,
    category VARCHAR(80) NOT NULL,
    body TEXT NOT NULL,
    published_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
  )
`;

await sql`
  CREATE TABLE IF NOT EXISTS comments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    article_slug TEXT NOT NULL REFERENCES articles(slug) ON DELETE CASCADE,
    parent_id BIGINT,
    message VARCHAR(2000) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (article_slug, id),
    FOREIGN KEY (article_slug, parent_id)
      REFERENCES comments(article_slug, id) ON DELETE CASCADE
  )
`;

await sql`
  CREATE INDEX IF NOT EXISTS comments_article_created_idx
  ON comments(article_slug, id)
`;

await sql`
  CREATE TABLE IF NOT EXISTS admin_login_attempts (
    ip_address VARCHAR(100) PRIMARY KEY,
    failed_attempts INTEGER NOT NULL DEFAULT 0,
    locked_until TIMESTAMPTZ
  )
`;

